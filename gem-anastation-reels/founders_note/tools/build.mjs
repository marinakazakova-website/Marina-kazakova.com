// FOUNDER'S NOTE — reusable closing slide (1080×1350).
// Fixed composition; each note changes only the NOTES entry: portrait, gem,
// headline, letter, CTA. Images are referenced, never altered (the portrait
// is only cropped by its frame).
//
// Usage: NODE_PATH=$(npm root -g) node tools/build.mjs [note-id]   (default: gems-of-asia)
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NOTES = {
  "gems-of-asia": {
    out: "GA_FoundersNote_gems_of_asia.png",
    portrait: "../gems_of_asia/sources/anastasia_portrait.webp", portraitPos: "62% 50%",
    gem: "../gems_of_asia/sources/gem_srilanka_blue_sapphire.png",
    gemCaption: "Blue Sapphire",
    rubric: "Curated by Nature",
    headline: "From Asia<br>to you.",
    letter: "Based in Bangkok, at the heart of Asia’s gemstone trade, I personally select exceptional gemstones for their natural beauty and individuality.",
    ctaLead: "Discover our collection.",
    ctaLine: "Private viewings by appointment<br>in Bangkok.",
  },
};
const id = process.argv[2] || "gems-of-asia";
const N = NOTES[id];
if (!N) throw new Error(`unknown note ${id}`);

// Rev. 4 (client): one editorial band — portrait and ivory text field joined
// edge to edge, full slide width (45 % / 55 %), square corners; navy above,
// navy below with the website line. Band: top 221, height 833.
const TOP = 221, PH = 833, PW = [486, 594];
const X0 = 0, GAP = 0;
const html = `<!doctype html>
<!-- Generated by tools/build.mjs (${id}) — edit NOTES there, not this file. -->
<html lang="en"><head><meta charset="utf-8"><title>Founder's Note</title>
<link rel="stylesheet" href="../founder/founder.css">
<style>
  :root { --navy: #102537; --teal: #1A4043; --gold2: #BBA375; }
  body { background: #d9d6d0; }
  .slide { width: 1080px; height: 1350px; background: var(--navy); position: relative; overflow: hidden; }
  /* top rubric — post rule: centred, text top y ≈ 112, AvantGarde caps 17 px, 0.42 em */
  .rubric { position: absolute; left: 0; width: 1080px; top: 112px; text-align: center; font-family: "AvantGarde";
            font-size: 17px; letter-spacing: .42em; text-indent: .42em; text-transform: uppercase;
            line-height: 1; color: var(--gold2); }
  .panel { position: absolute; top: ${TOP}px; height: ${PH}px; overflow: hidden; }   /* square corners */
  .p1 { left: ${X0}px; width: ${PW[0]}px; }
  .p1 img { width: 100%; height: 100%; object-fit: cover; object-position: ${N.portraitPos}; display: block; }
  .p2 { left: ${X0 + PW[0] + GAP}px; width: ${PW[1]}px; background: var(--ivory); color: var(--navy); }
  .p2 .in { position: absolute; left: 64px; right: 56px; top: 0; bottom: 0; }
  .hr { position: absolute; left: 0; height: 1px; background: var(--gold2); }
  .h1 { position: absolute; left: 0; top: 92px; margin: 0; font-family: "Didot Italic"; font-style: italic;
        font-weight: 400; font-size: 66px; line-height: 1.04; color: var(--navy); }
  .letter { position: absolute; left: 0; top: 284px; width: 440px; margin: 0; font-family: "AvantGarde";
        font-size: 22px; line-height: 1.5; color: var(--navy); }
  .lead { position: absolute; left: 0; top: 498px; font-family: "Didot Italic"; font-style: italic;
        font-size: 42px; line-height: 1.08; color: var(--teal); }
  .line { position: absolute; left: 0; top: 558px; width: 440px; font-family: "AvantGarde";
        font-size: 21px; line-height: 1.45; color: var(--navy); }
  .name { position: absolute; left: 0; top: 712px; font-family: "Didot Title"; font-size: 30px;
        letter-spacing: .24em; color: var(--gold2); }
  .role { position: absolute; left: 0; top: 760px; font-family: "AvantGarde"; font-size: 13px;
        letter-spacing: .28em; text-transform: uppercase; color: var(--navy); opacity: .8; }
</style></head>
<body><section class="slide" id="note">
  ${N.rubric ? `<div class="rubric">${N.rubric}</div>` : ""}
  <div class="panel p1"><img src="${N.portrait}" alt="Anastasia"></div>
  <div class="panel p2"><div class="in">
    <div class="hr" style="top:52px; width:90px"></div>
    <h1 class="h1">${N.headline}</h1>
    <p class="letter">${N.letter}</p>
    <div class="hr" style="top:464px; width:64px"></div>
    <div class="lead">${N.ctaLead}</div>
    <div class="line">${N.ctaLine}</div>
    <div class="name">ANASTASIA</div>
    <div class="role">Founder &amp; Gem Expert</div>
  </div></div>
  <img src="build/url_on_navy.png" style="position:absolute; left:375px; top:1223px" width="351" height="23" alt="www.gemanastation.com">
</section></body></html>`;
fs.writeFileSync(path.join(root, `note_${id}.html`), html);

const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ args: ["--force-color-profile=srgb"] });
const page = await browser.newPage({ viewport: { width: 1080, height: 1350 }, deviceScaleFactor: 1 });
await page.goto("file://" + path.join(root, `note_${id}.html`));
await page.evaluate(() => document.fonts.ready);
await page.waitForLoadState("networkidle");
await page.locator("#note").screenshot({ path: path.join(root, "output", N.out) });
await browser.close();
console.log("written output/" + N.out);
