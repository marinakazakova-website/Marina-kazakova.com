// FOUNDER'S NOTE — reusable closing slide (1080×1350).
// Fixed composition; each note changes only the NOTES entry: portrait, gem,
// headline, letter, CTA. Images are referenced, never altered (the portrait
// is only cropped by its frame).
//
// Usage: NODE_PATH=$(npm root -g) node tools/build.mjs [note-id]   (default: gems-of-asia)
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NOTES = {
  "gems-of-asia": {
    out: "GA_FoundersNote_gems_of_asia.png",
    portrait: "../gems_of_asia/sources/anastasia_portrait.webp", portraitPos: "50% 0%",
    gem: "../gems_of_asia/sources/gem_srilanka_blue_sapphire.png",
    gemCaption: "Blue Sapphire",
    headline: "From Asia<br>to you.",
    letter: "Based in Bangkok, at the heart of Asia’s gemstone trade, I personally select exceptional gemstones for their natural beauty and individuality.",
    ctaLead: "Discover our collection.",
    ctaLine: "Private viewings by appointment<br>in Bangkok.",
  },
};
const id = process.argv[2] || "gems-of-asia";
const N = NOTES[id];
if (!N) throw new Error(`unknown note ${id}`);

const html = `<!doctype html>
<!-- Generated by tools/build.mjs (${id}) — edit NOTES there, not this file. -->
<html lang="en"><head><meta charset="utf-8"><title>Founder's Note</title>
<link rel="stylesheet" href="../founder/founder.css">
<style>
  :root { --navy: #102537; --turq: #439090; --gold2: #BBA375; }
  body { background: #d9d6d0; }
  .slide { width: 1080px; height: 1350px; background: var(--ivory); position: relative; overflow: hidden; color: var(--navy); }
  .a { position: absolute; }

  /* Portrait: small vertical frame, upper left (≈ 10 % of the page) */
  .portrait { left: 96px; top: 112px; width: 330px; height: 430px; overflow: hidden; }
  .portrait img { width: 100%; height: 100%; object-fit: cover; object-position: ${N.portraitPos}; display: block; }

  /* Gem: free-standing object, higher and to the right — a second level */
  .gem { left: 600px; top: 196px; width: 330px; height: 330px; }
  .gem img { width: 100%; height: 100%; object-fit: contain; display: block;
    filter: drop-shadow(0 18px 22px rgba(16,37,55,.16)); }
  .gemcap { left: 600px; width: 330px; top: 560px; text-align: center; font-family: "Mono"; font-size: 14px;
    letter-spacing: .24em; text-transform: uppercase; color: var(--gold2); }

  .headline { left: 96px; top: 640px; margin: 0; font-weight: 400; font-style: normal;
    font-family: "Didot Title"; font-size: 100px; line-height: .98;
    letter-spacing: .03em; text-transform: uppercase; color: var(--navy); }

  .letter { left: 96px; top: 880px; width: 470px; font-family: "AvantGarde"; font-size: 22px; line-height: 1.6; color: var(--navy); }

  /* CTA: its own column, a short turquoise rule, an italic invitation */
  .cta { left: 620px; top: 884px; width: 364px; }
  .cta .rule2 { width: 48px; height: 1px; background: var(--turq); margin-bottom: 22px; }
  .cta .lead { font-family: "Didot Italic"; font-style: italic; font-size: 32px; line-height: 1.15; color: var(--navy); }
  .cta .line { margin-top: 12px; font-family: "AvantGarde"; font-size: 19px; line-height: 1.5; color: var(--turq); }

  /* Signature — approved founder style */
  .sig { left: 96px; top: 1092px; }
  .sig .name { font-family: "Didot Title"; font-size: 24px; letter-spacing: .32em; color: var(--gold2); }
  .sig .role { margin-top: 10px; font-family: "Mono"; font-size: 15px; letter-spacing: .2em; text-transform: uppercase; color: var(--gold2); }
</style></head>
<body><section class="slide" id="note">
  <div class="a portrait"><img src="${N.portrait}" alt="Anastasia"></div>
  <div class="a gem"><img src="${N.gem}" alt="${N.gemCaption}"></div>
  <div class="a gemcap">${N.gemCaption}</div>

  <h1 class="a headline">${N.headline}</h1>
  <p class="a letter">${N.letter}</p>
  <div class="a cta"><div class="rule2"></div><div class="lead">${N.ctaLead}</div><div class="line">${N.ctaLine}</div></div>

  <div class="a sig"><div class="name">ANASTASIA</div><div class="role">Founder &amp; Gem Expert</div></div>
  <img src="../founder/build/url_on_light.png" style="position:absolute; left:375px; top:1223px" width="351" height="23" alt="www.gemanastation.com">
</section></body></html>`;
fs.writeFileSync(path.join(root, `note_${id}.html`), html);

const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ args: ["--force-color-profile=srgb"] });
const page = await browser.newPage({ viewport: { width: 1080, height: 1350 }, deviceScaleFactor: 1 });
await page.goto("file://" + path.join(root, `note_${id}.html`));
await page.evaluate(() => document.fonts.ready);
await page.waitForLoadState("networkidle");
await page.locator("#note").screenshot({ path: path.join(root, "output", N.out) });
await browser.close();
console.log("written output/" + N.out);
