// FOUNDER'S NOTE — reusable closing slide (1080×1350).
// Fixed composition; each note changes only the NOTES entry: portrait, gem,
// headline, letter, CTA. Images are referenced, never altered (the portrait
// is only cropped by its frame).
//
// Usage: NODE_PATH=$(npm root -g) node tools/build.mjs [note-id]   (default: gems-of-asia)
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NOTES = {
  "gems-of-asia": {
    out: "GA_FoundersNote_gems_of_asia.png",
    portrait: "../gems_of_asia/sources/anastasia_portrait.webp", portraitPos: "46% 50%",
    gem: "../gems_of_asia/sources/gem_srilanka_blue_sapphire.png",
    gemCaption: "Blue Sapphire",
    headline: "From Asia<br>to you.",
    letter: "Based in Bangkok, at the heart of Asia’s gemstone trade, I personally select exceptional gemstones for their natural beauty and individuality.",
    ctaLead: "Discover<br>our collection.",
    ctaLine: "Private viewings by appointment in Bangkok.",
  },
};
const id = process.argv[2] || "gems-of-asia";
const N = NOTES[id];
if (!N) throw new Error(`unknown note ${id}`);

// Geometry from the client reference (1092 × 1440), scaled to 1080 wide and
// fitted between the top air and the website line: three panels, 15 px gaps.
const TOP = 221, PH = 833;                          // panel top and height
const P = [[20, 326], [361, 358], [734, 326]];      // [x, width] left / centre / right
const html = `<!doctype html>
<!-- Generated by tools/build.mjs (${id}) — edit NOTES there, not this file. -->
<html lang="en"><head><meta charset="utf-8"><title>Founder's Note</title>
<link rel="stylesheet" href="../founder/founder.css">
<style>
  :root { --navy: #102537; --teal: #1A4043; --gold2: #BBA375; }
  body { background: #d9d6d0; }
  .slide { width: 1080px; height: 1350px; background: var(--navy); position: relative; overflow: hidden; }
  .panel { position: absolute; top: ${TOP}px; height: ${PH}px; border-radius: 18px; overflow: hidden; }
  .p1 { left: ${P[0][0]}px; width: ${P[0][1]}px; }
  .p1 img { width: 100%; height: 100%; object-fit: cover; object-position: ${N.portraitPos}; display: block; }
  .p2 { left: ${P[1][0]}px; width: ${P[1][1]}px; background: var(--ivory); color: var(--navy); }
  .p3 { left: ${P[2][0]}px; width: ${P[2][1]}px;
        background: radial-gradient(120% 80% at 50% 62%, #F3EEE5 0%, #E4DBCB 70%, #D6CBB8 100%); }
  .p3 img { position: absolute; left: 50%; top: 61%; width: 76%; transform: translate(-50%, -50%);
            filter: drop-shadow(0 22px 20px rgba(16,37,55,.28)); }   /* scaled only, never reshaped */

  .p2 .in { position: absolute; left: 38px; right: 30px; top: 0; bottom: 0; }
  .hr { position: absolute; left: 0; height: 1px; background: var(--gold2); }
  .h1 { position: absolute; left: 0; top: 84px; margin: 0; font-family: "Didot Title"; font-weight: 400;
        font-size: 47px; line-height: 1.06; letter-spacing: -.005em; text-transform: uppercase; color: var(--navy); }
  .letter { position: absolute; left: 0; top: 232px; width: 290px; margin: 0; font-family: "AvantGarde";
        font-size: 22px; line-height: 1.42; color: var(--navy); }
  .lead { position: absolute; left: 0; top: 476px; font-family: "Didot Italic"; font-style: italic;
        font-size: 40px; line-height: 1.08; color: var(--teal); }
  .line { position: absolute; left: 0; top: 576px; width: 290px; font-family: "AvantGarde";
        font-size: 21px; line-height: 1.42; color: var(--navy); }
  .name { position: absolute; left: 0; top: 716px; font-family: "Didot Title"; font-size: 30px;
        letter-spacing: .2em; color: var(--gold2); }
  .role { position: absolute; left: 0; top: 762px; font-family: "AvantGarde"; font-size: 13px;
        letter-spacing: .26em; text-transform: uppercase; color: var(--navy); opacity: .8; }
</style></head>
<body><section class="slide" id="note">
  <div class="panel p1"><img src="${N.portrait}" alt="Anastasia"></div>
  <div class="panel p2"><div class="in">
    <div class="hr" style="top:48px; width:90px"></div>
    <h1 class="h1">${N.headline}</h1>
    <p class="letter">${N.letter}</p>
    <div class="hr" style="top:446px; width:64px"></div>
    <div class="lead">${N.ctaLead}</div>
    <div class="line">${N.ctaLine}</div>
    <div class="name">ANASTASIA</div>
    <div class="role">Founder &amp; Gem Expert</div>
  </div></div>
  <div class="panel p3"><img src="${N.gem}" alt="${N.gemCaption}"></div>
  <img src="build/url_on_navy.png" style="position:absolute; left:375px; top:1223px" width="351" height="23" alt="www.gemanastation.com">
</section></body></html>`;
fs.writeFileSync(path.join(root, `note_${id}.html`), html);

const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ args: ["--force-color-profile=srgb"] });
const page = await browser.newPage({ viewport: { width: 1080, height: 1350 }, deviceScaleFactor: 1 });
await page.goto("file://" + path.join(root, `note_${id}.html`));
await page.evaluate(() => document.fonts.ready);
await page.waitForLoadState("networkidle");
await page.locator("#note").screenshot({ path: path.join(root, "output", N.out) });
await browser.close();
console.log("written output/" + N.out);
